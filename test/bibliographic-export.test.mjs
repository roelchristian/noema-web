import test from 'node:test';
import assert from 'node:assert/strict';
import {openDatabase} from '../src/server/database.ts';
import {Store} from '../src/server/store.ts';
import {Knowledge} from '../src/server/modules/knowledge.ts';
import {PropertyReview} from '../src/server/modules/property-review.ts';
import {proposeValue,rawSourceHash} from '../src/server/modules/property-provenance.ts';
import {exportBibliographicBundle} from '../src/server/modules/bibliographic-export.ts';
import {TAXONOMY_VERSION,DOMAINS} from '../src/shared/domains.ts';
import {parseBibliography} from '../src/shared/bibliography.ts';

test('annotated exports distinguish reviewed scholarly interpretation from author abstracts; sidecar retains evidence once',()=>{
 const db=openDatabase(':memory:'),store=new Store(db),knowledge=new Knowledge(store),review=new PropertyReview(store);
 try {
  store.run("INSERT INTO entities(id,vault_id,name,type,updated_at) VALUES('synthetic-source','default','Synthetic publication','source','2026-10-24')");
  const source={id:'synthetic-source'},target=knowledge.create('default',{name:'Synthetic earlier edition',type:'creativework'});
  const evidence={source_file_id:'synthetic-file',source_hash:rawSourceHash('Synthetic supporting evidence')};
  store.run("INSERT INTO source_files(id,vault_id,entity_id,name,size,status,text,created_at,format,admitted) VALUES('synthetic-file','default',?,'Synthetic.txt',1,'ready','Synthetic supporting evidence','2026-10-24','txt',1)",source.id);
  const raw='@book{synthetic,title={Synthetic publication}}';
  const record={sourceId:source.id,citationKey:'synthetic',entryType:'book',fields:{title:'Synthetic publication',abstract:'Actual author abstract',annotation:'Authored annotation',keywords:'authored'},provenance:{title:{origin:'bibtex'},abstract:{origin:'manual'}},rawImports:[raw],revision:1};
  const synopsis=JSON.stringify({basis:'document-excerpts',text:'Interprets {ideals} & evidence 50% \\input{evil}',method:'Comparison',conclusions:'Limited to excerpts',quote:'Synthetic supporting evidence',suggestedDisciplines:[{domainId:'general',quote:'Synthetic supporting evidence'}]});
  const proposed=proposeValue(store,'default',{entity_id:source.id,...evidence,property_name:'ai scholarly synopsis',value:synopsis,origin:'ai',details:'Synthetic supporting evidence'});
  const pending=proposeValue(store,'default',{entity_id:source.id,property_name:'scholarly critiques',target_id:target.id,origin:'ai',details:'Pending evidence'});
  let bundle=exportBibliographicBundle(store,'default',[record],[]);
  assert.equal(bundle.annotatedBiblatex,bundle.biblatex);
  const item=review.list('default',source.id).find(item=>item.id===proposed.id);
  review.review('default',source.id,item.id,{action:'accept',fingerprint:item.fingerprint});
  store.run('INSERT INTO relationships(id,source_id,label,target_id) VALUES(?,?,?,?)','work-link',source.id,'edition of',target.id);
  bundle=exportBibliographicBundle(store,'default',[record],[]);
  assert.ok(bundle.annotatedBiblatex.includes('Noema AI synopsis; reviewed; based on document excerpts'));
  assert.ok(bundle.annotatedBiblatex.includes('Authored annotation'));
  assert.ok(bundle.annotatedBiblatex.includes('\\textbackslash{}input\\{evil\\}'));
  let annotated=parseBibliography(bundle.annotatedBiblatex).entries[0];
  assert.equal(annotated.fields.abstract,'Actual author abstract');
  assert.equal(annotated.fields.keywords,'authored','accepting a synopsis does not accept suggested disciplines');
  assert.ok(!bundle.bibtex.includes('Noema AI synopsis'));
  const classification=proposeValue(store,'default',{entity_id:source.id,...evidence,property_name:'scholarly discipline',value:JSON.stringify({domainId:'general',label:'General',taxonomyVersion:TAXONOMY_VERSION,bibliographicRevision:null}),origin:'ai',details:'source-scholarly-v2:'+('a'.repeat(64))+'\nDiscipline evidence'});
  const discipline=review.list('default',source.id).find(item=>item.id===classification.id);
  review.review('default',source.id,discipline.id,{action:'accept',fingerprint:discipline.fingerprint});
  bundle=exportBibliographicBundle(store,'default',[record],[]);
  annotated=parseBibliography(bundle.annotatedBiblatex).entries[0];
  assert.equal(annotated.fields.keywords,'authored, '+DOMAINS.find(domain=>domain.id==='general').label);
  const sidecar=JSON.parse(bundle.sidecar),scholarly=sidecar.records[0].scholarly;
  assert.equal(sidecar.importBatches.length,1);
  assert.equal(sidecar.importBatches[0].raw,raw);
  assert.equal(sidecar.records[0].rawImportIds[0],sidecar.importBatches[0].id);
  assert.equal(sidecar.records[0].rawImports,undefined);
  assert.equal(scholarly.reviewedProposals.length,2);
  assert.ok(!scholarly.reviewedProposals.some(proposal=>proposal.id===pending.id));
  assert.equal(scholarly.acceptedProperties[0].provenance.origin,'ai');
  assert.equal(scholarly.classifications[0].canonical,true);
  assert.equal(scholarly.classifications[0].proposalIds[0],classification.id);
  assert.equal(scholarly.suggestedClassifications[0].status,'suggested');
  assert.equal(scholarly.relationships[0].targetId,target.id);
  assert.deepEqual(exportBibliographicBundle(store,'default',[record],[]),bundle);
  store.run('UPDATE property_provenance SET stale=1 WHERE property_id=?',scholarly.acceptedProperties[0].id);
  const stale=exportBibliographicBundle(store,'default',[record],[]);
  assert.ok(!stale.annotatedBiblatex.includes('Noema AI synopsis'));
  assert.equal(JSON.parse(stale.sidecar).records[0].scholarly.acceptedProperties[0].provenance.stale,true);
 }finally{db.close();}
});
